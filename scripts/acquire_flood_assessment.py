def sha(data):
    return hashlib.sha256(data).hexdigest()

def dump(path, value):
    pending = path.with_name(path.name + '.pending')
    pending.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    pending.replace(path)

receipts = []

def acquire(name, url):
    path = ORIGINALS / name
    receipt_path = ORIGINALS / (name + '.receipt.json')
    if path.exists():
        if not receipt_path.exists():
            raise RuntimeError('Preserved original lacks its acquisition receipt: ' + name)
        data = path.read_bytes()
        rec = json.loads(receipt_path.read_text(encoding='utf-8'))
        assert rec['url'] == url and rec['sha256'] == sha(data)
    else:
        expected = json.loads(receipt_path.read_text(encoding='utf-8')) if receipt_path.exists() else None
        if expected is not None:
            assert expected['url'] == url
        request = urllib.request.Request(url, headers={'User-Agent': 'DrainCheck-public-source-audit/1.0'})
        with urllib.request.urlopen(request, timeout=45) as response:
            data = response.read(40 * 1024 * 1024 + 1)
            headers = dict(response.headers)
        assert len(data) <= 40 * 1024 * 1024
        if expected is not None and (expected['sha256'] != sha(data) or expected['size_bytes'] != len(data)):
            raise ValueError('Public source changed from the preserved snapshot; no original or receipt was overwritten: ' + name)
        with path.open('xb') as stream:
            stream.write(data)
        rec = expected if expected is not None else {'file': path.relative_to(ROOT).as_posix(), 'url': url,
               'sha256': sha(data), 'size_bytes': len(data), 'retrieved_utc': NOW,
               'response_headers': headers}
        dump(receipt_path, rec)
    # Keep the exact acquisition receipt locally, but never publish HTTP account
    # state, even when it was generated by an otherwise public GIS endpoint.
    private_headers = {'set-cookie', 'cookie', 'authorization', 'proxy-authorization'}
    removed = [key for key in rec.get('response_headers', {}) if key.lower() in private_headers]
    if removed:
        private_path = ORIGINALS / (name + '.receipt.private.json')
        if not private_path.exists():
            private_path.write_bytes(receipt_path.read_bytes())
        rec = dict(rec)
        rec['response_headers'] = {k: v for k, v in rec.get('response_headers', {}).items() if k.lower() not in private_headers}
        rec['response_header_names_redacted'] = sorted(removed)
        dump(receipt_path, rec)
    receipts.append(rec)
    return data

