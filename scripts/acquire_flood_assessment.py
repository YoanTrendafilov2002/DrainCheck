def vertices(geometry):
    if 'geometries' in geometry:
        return set().union(*(vertices(g) for g in geometry['geometries']))
    result = set()
    def walk(value):
        if value and isinstance(value[0], (int, float)):
            result.add(tuple(value))
        else:
            for item in value:
                walk(item)
    walk(geometry['coordinates'])
    return result

def area_parts(geometry):
    if geometry.geom_type == 'Polygon':
        return [geometry]
    if geometry.geom_type in {'MultiPolygon', 'GeometryCollection'}:
        return [p for g in geometry.geoms for p in area_parts(g)]
    return []

def non_area_parts(geometry):
    if geometry.geom_type in {'Polygon', 'MultiPolygon'}:
        return []
    if geometry.geom_type == 'GeometryCollection':
        return [p for g in geometry.geoms for p in non_area_parts(g)]
    return [geometry]

for feature in zones:
    original = shape(feature['geometry'])
    repaired = make_valid(original)
    polygons = area_parts(repaired)
    non_area = non_area_parts(repaired)
    assert polygons
    area_geometry = polygons[0] if len(polygons) == 1 else MultiPolygon(polygons)
    assert area_geometry.is_valid and not area_geometry.is_empty
    projected_original = transform(projection, original)
    projected_repaired = transform(projection, area_geometry)
    before_vertices = vertices(feature['geometry'])
    after_vertices = vertices(mapping(area_geometry))
    props = dict(feature['properties'])
    props['geometry_repaired'] = not original.is_valid
    props['geometry_repair_method'] = 'GEOS make_valid in source WGS84; all polygon components retained; no simplification/buffer'
    display.append({'type': 'Feature', 'properties': props, 'geometry': mapping(area_geometry)})
    # The browser copy is separate from the validated full-precision geometry.
    # Never use it for hit predicates, raster masks, area or exposure analysis.
    browser_projected = projected_repaired.simplify(1.0, preserve_topology=True)
    browser_geometry = transform(Transformer.from_crs(7801, 4326, always_xy=True).transform, browser_projected)
    assert browser_geometry.is_valid and not browser_geometry.is_empty
    assert len(area_parts(browser_projected)) == len(polygons)
    assert sum(len(p.interiors) for p in area_parts(browser_projected)) == sum(len(p.interiors) for p in polygons)
