def coordinates(element):
    triples = [tuple(map(float, part.split(','))) for part in element.text.split()]
    assert all(len(p) == 2 or (len(p) == 3 and p[2] == 0) for p in triples)
    return [list(p[:2]) for p in triples]

def kml_geometry(element):
    kind = element.tag.split('}')[-1]
    if kind == 'Point':
        return {'type': 'Point', 'coordinates': coordinates(element.find('k:coordinates', ns))[0]}
    if kind == 'LineString':
        return {'type': 'LineString', 'coordinates': coordinates(element.find('k:coordinates', ns))}
    if kind == 'Polygon':
        rings = [coordinates(element.find('k:outerBoundaryIs/k:LinearRing/k:coordinates', ns))]
        rings.extend(coordinates(e) for e in element.findall('k:innerBoundaryIs/k:LinearRing/k:coordinates', ns))
        return {'type': 'Polygon', 'coordinates': rings}
    if kind == 'MultiGeometry':
        parts = [kml_geometry(c) for c in element]
        kinds = {p['type'] for p in parts}
        if kinds == {'LineString'}:
            return {'type': 'MultiLineString', 'coordinates': [p['coordinates'] for p in parts]}
        if kinds == {'Polygon'}:
            return {'type': 'MultiPolygon', 'coordinates': [p['coordinates'] for p in parts]}
        return {'type': 'GeometryCollection', 'geometries': parts}
    raise ValueError(kind)

